import fs from "node:fs";
import path from "node:path";

// The API drops the second family when two f[] params are combined, so request each family separately.
const families = ["cabinet-grotesk@500,700,800", "satoshi@400,500,700"];
let css = "";
for (const f of families) {
  css += await (
    await fetch(`https://api.fontshare.com/v2/css?f[]=${f}&display=swap`, {
      headers: { "User-Agent": "Mozilla/5.0" },
    })
  ).text();
}

fs.mkdirSync("public/fonts", { recursive: true });
const blocks = css.match(/@font-face\s*{[^}]*}/g) ?? [];
if (blocks.length === 0) throw new Error("No @font-face blocks returned");

let out = "/* Generated by scripts/fetch-fonts.mjs. Fonts: Fontshare, free for commercial use. */\n";
for (const block of blocks) {
  const family = /font-family:\s*['"]?([^;'"]+)/.exec(block)[1].trim();
  const weight = /font-weight:\s*([0-9]+)/.exec(block)[1];
  const url = /url\(['"]?([^'")]+\.woff2[^'")]*)['"]?\)/.exec(block)[1];
  const file = `${family.toLowerCase().replace(/\s+/g, "-")}-${weight}.woff2`;
  const res = await fetch(url.startsWith("//") ? `https:${url}` : url);
  fs.writeFileSync(path.join("public/fonts", file), Buffer.from(await res.arrayBuffer()));
  out += `@font-face{font-family:"${family}";font-weight:${weight};font-style:normal;font-display:swap;src:url("/fonts/${file}") format("woff2");}\n`;
  console.log("saved", file);
}
fs.writeFileSync("src/app/fonts.css", out);
